import os
import json
import uvicorn
import time
from fastapi import FastAPI, Request, BackgroundTasks
from groq import Groq
import httpx
import mcp_server

app = FastAPI(title="DQ Agent Runtime - Hybrid")

@app.get("/ping")
async def ping():
    return {"status": "ok"}

@app.post("/configs")
async def save_config(request: Request):
    try:
        body = await request.json()
        config_text = body.get("config_text", "")
        mcp_server.save_custom_config(config_text)
        return {"status": "success", "message": "Config saved"}
    except Exception as e:
        import traceback
        return {"status": "error", "message": str(e), "traceback": traceback.format_exc()}

def process_profiles_background(profiles_list, system_prompt, deterministic_rules=[]):
    # First, save any deterministic rules generated by the Semantic Router
    if deterministic_rules:
        try:
            mcp_server.save_rules_bulk(json.dumps(deterministic_rules))
            print(f"Saved {len(deterministic_rules)} deterministic rules.")
        except Exception as e:
            print(f"Error saving deterministic rules: {e}")

    if not profiles_list:
        print("No profiles left for LLM processing.")
        return

    http_client = httpx.Client(verify=False)
    client = Groq(api_key=os.environ.get("GROQ_API_KEY"), http_client=http_client)
    
    # Batch the profiles into chunks of 8 (since they are more complex now)
    chunk_size = 8
    batches = [profiles_list[i:i + chunk_size] for i in range(0, len(profiles_list), chunk_size)]
    
    for batch in batches:
        retries = 3
        while retries > 0:
            try:
                # To save tokens, we could strip out some verbose fields, 
                # but we'll leave them for now to give LLM maximum context on the filtered columns.
                chat_completion = client.chat.completions.create(
                    messages=[
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": json.dumps(batch)}
                    ],
                    model="llama-3.1-8b-instant",
                    temperature=0.1,
                )
                
                generated_rules_json = chat_completion.choices[0].message.content
                
                if generated_rules_json.startswith("```"):
                    generated_rules_json = generated_rules_json.strip('`').replace('json\n', '').strip()
                    
                try:
                    raw_rules = json.loads(generated_rules_json)
                    valid_rules = []
                    
                    for rule in raw_rules:
                        # 1. Enhanced Validation Shield
                        profile = next((p for p in batch if p['table_name'] == rule['table_name'] and p['column_name'] == rule['column_name']), None)
                        
                        if not profile:
                            continue
                            
                        rt = rule.get('rule_type')
                        dt = profile.get('data_type', '').lower()
                        col_name = rule['column_name'].lower()
                        
                        # Mathematical constraints against the profile
                        if rt == 'not_null' and profile.get('null_rate', 0) > 0.05:
                            continue
                        if rt == 'unique' and profile.get('distinct_rate', 0) < 0.95:
                            continue
                        if rt == 'unique' and ('date' in dt or 'time' in dt or 'bool' in dt):
                            continue
                        if rt == 'accepted_values':
                            config_vals = rule.get('rule_config', {}).get('values', [])
                            if not config_vals or config_vals == ["1", "2", "3", "4", "5"]:
                                continue
                        if rt == 'regex_match' and not rule.get('rule_config', {}).get('regex'):
                            continue
                        if rt in ['min_value', 'max_value'] and ('char' in dt or 'text' in dt):
                            continue
                            
                        valid_rules.append(rule)
                        
                    if valid_rules:
                        mcp_server.save_rules_bulk(json.dumps(valid_rules))
                        
                except json.JSONDecodeError:
                    print("Failed to decode JSON from LLM")
                
                break
                
            except Exception as e:
                print(f"Error processing batch: {e}")
                retries -= 1
                if retries > 0:
                    time.sleep(15)
            
        time.sleep(2.5)


@app.post("/invocations")
async def generate_rules(request: Request, background_tasks: BackgroundTasks):
    try:
        profiles_json = mcp_server.get_profiles()
        all_profiles = json.loads(profiles_json)
        
        ignore_tables = {"dq_rules", "dq_profiles", "dq_violations", "dq_rules_proposed", "dq_business_configs"}
        profiles_list = [p for p in all_profiles if p.get("table_name") not in ignore_tables]

        # ---------------------------------------------------------
        # SEMANTIC ROUTER LOGIC
        # ---------------------------------------------------------
        llm_profiles = []
        deterministic_rules = []
        
        for profile in profiles_list:
            col_name = profile.get("column_name", "").lower()
            dt = profile.get("data_type", "").lower()
            table_name = profile.get("table_name")
            
            # 1. Ignore Unstructured Text completely
            if any(term in col_name for term in ['description', 'notes', 'comments', 'bio']):
                continue
                
            # 2. Deterministic Identifiers (PKs)
            if col_name == 'id' or (col_name.endswith('_id') and profile.get('distinct_rate', 0) > 0.95):
                # We definitively know this is an ID. Generate deterministic rules.
                deterministic_rules.append({
                    "table_name": table_name,
                    "column_name": profile.get("column_name"),
                    "rule_type": "not_null",
                    "severity": "high",
                    "confidence": 1.0,
                    "rule_config": {},
                    "dq_type": "Completeness"
                })
                if profile.get('distinct_rate', 0) > 0.95:
                    deterministic_rules.append({
                        "table_name": table_name,
                        "column_name": profile.get("column_name"),
                        "rule_type": "unique",
                        "severity": "high",
                        "confidence": 1.0,
                        "rule_config": {},
                        "dq_type": "Uniqueness"
                    })
                # Skip LLM for this column since we already handled it perfectly.
                continue
                
            # 3. Deterministic Booleans
            if 'bool' in dt:
                deterministic_rules.append({
                    "table_name": table_name,
                    "column_name": profile.get("column_name"),
                    "rule_type": "accepted_values",
                    "severity": "medium",
                    "confidence": 1.0,
                    "rule_config": {"values": ["true", "false", "True", "False", "1", "0", "t", "f", "TRUE", "FALSE"]},
                    "dq_type": "Validity"
                })
                continue

            # 4. Route everything else to the LLM (emails, statuses, prices, dates)
            llm_profiles.append(profile)

        # ---------------------------------------------------------
        
        system_prompt = """
        You are an expert Data Quality Engineer. Analyze the database profiles and generate comprehensive data quality rules covering the core dimensions of Data Quality.
        
        CRITICAL INSTRUCTIONS:
        1. ONLY use these rule_type values: "not_null", "unique", "min_value", "max_value", "accepted_values", "regex_match", "min_length", "max_length", "freshness".
        2. Do NOT generate a "unique" rule if the distinct_rate is less than 0.95.
        3. Do NOT generate a "not_null" rule if the null_rate is significantly greater than 0.
        4. "rule_config" formats:
           - min/max_value: {"min_value": X} or {"max_value": Y}
           - accepted_values: {"values": ["A", "B"]}
           - regex_match: {"regex": "^[a-z]+$"}
           - min/max_length: {"min_length": X}
           - freshness: {"max_days_old": X}
        5. The "dq_type" field MUST be one of the 6 core dimensions: Completeness, Uniqueness, Validity, Accuracy, Consistency, Timeliness.
        
        Return ONLY a raw JSON array matching this exact schema:
        [
          {
            "table_name": "string",
            "column_name": "string",
            "rule_type": "string",
            "severity": "string",
            "confidence": 0.9,
            "rule_config": {},
            "dq_type": "string"
          }
        ]
        Do not include any markdown formatting or explanations. Just the JSON array.
        """
        
        custom_config = mcp_server.get_all_configs_text()
        if custom_config and custom_config.strip():
            system_prompt += f"""
        
        CRITICAL BUSINESS CONSTRAINTS TO ENFORCE:
        {custom_config.strip()}
        
        When generating rules, ensure your `rule_config` strictly adheres to the business constraints provided above.
        """
        
        background_tasks.add_task(process_profiles_background, llm_profiles, system_prompt, deterministic_rules)
        
        return {
            "status": "success", 
            "message": f"Hybrid engine started! Handled {len(profiles_list) - len(llm_profiles)} columns deterministically. Routed {len(llm_profiles)} columns to LLM in the background."
        }
            
    except Exception as e:
        import traceback
        return {
            "status": "error", 
            "message": str(e),
            "traceback": traceback.format_exc()
        }

if __name__ == "__main__":
    uvicorn.run(app, host="0.0.0.0", port=8080)
